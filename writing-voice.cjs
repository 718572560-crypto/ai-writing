'use strict';

const styleGuides={
  '自然叙述':'像一个认真观察生活的人在和读者说清一件事。保留判断的分寸和细节，让观点从材料里长出来；允许一句话说短，也允许复杂处讲透，不追求句句漂亮。',
  '温暖治愈':'语气温和，但不替读者宣布“都会好起来”，不把具体难处包装成励志结论。让体谅来自看见处境、顾虑和两难；温暖可以克制，结尾可以留白。',
  '专业理性':'准确、清晰、有判断。说明事实与推论的边界；需要有结构时把层次说清，但不要写成报告、会议纪要或教科书，也要交代变化对真实生活意味着什么。',
  '轻松幽默':'观察准确，幽默轻一点，最好来自事情本身的反差。不要每段都抖机灵，不硬造梗、不模仿网络腔；涉及伤害、疾病、贫困等严肃处境时不用当事人的痛苦做笑点。',
  '简洁有力':'删掉空转的铺垫和重复判断，把关键事实与人的代价说清。短句可以落锤，长句用来解释复杂关系；不要把全文切成口号、金句或一串断句。'
};

const craftPrinciples=`写作原则：
- 先从材料中找出真正值得讲的矛盾、选择、代价或变化，再决定文章如何展开。不要套用固定的“背景—分析—建议—总结”框架，也不要预设必须有几段、几节或几个小标题。
- 让情绪有来处：优先呈现材料已经提供的处境、关系、限制、得失和细节，再写它可能触及的普通人感受。不要把“有共情”写成替别人哭、替读者下结论或密集堆形容词。
- 节奏跟着内容走：叙事、解释、判断与停顿交替出现；长短句和段落可有变化，关键处可以收紧，复杂处可以展开。避免连续使用同一种句型、对称段落、固定转折词和每段一句观点加一句总结。
- 开头选择最有辨识度的事实、细节、反差或问题，不写套话式背景介绍。中段允许出现新的信息或修正先前判断；结尾不重复全文、不强行升华、不默认用反问句。
- 文章可以有鲜明立场，也可以保留矛盾和未完成之处。不要为了“有起伏”制造冲突，不要为了“有温度”伪造真人经历、对白、心理活动、场景、数字或事实。
- 第一人称仅用于用户明确提供的作者经历或观点。没有个人经历时，用清楚的观察和有依据的分析建立真实感，不假装亲历。
- 参考原文是事实核对和理解主题的材料，不照搬其句子、结构、修辞和结论。不能独立核实的新事实不添加；将事实、推断、观点与待核实信息分开表达。
- 标题可用但不强制 Markdown 一级标题；正文只在确有助于阅读时加小标题。按用户目标字数写足必要内容，不灌水、不为凑数反复总结。`;

const titleCraft=`标题的人情味：
- 从材料里具体的人、关系、顾虑、愿望、选择或生活细节切入，让读者知道“这与我的生活有什么关系”。材料没有人物时，从使用者的真实问题切入，不强塞亲情故事。
- 先比较不同切口，再选有辨识度、像人在认真说话的表达。少用“深度解析、几点建议、重磅、看完泪目”等空泛包装，不靠渲染苦难、道德绑架、隐瞒关键信息或承诺结果制造点击。
- 人情味来自准确体谅处境，不等于替当事人断言感受。标题不能新增正文没有的亲历、亲属关系、对白、身份、数字或结局；正文必须兑现标题。陈述、细节和自然疑问都可以，不把所有标题写成反问，不统一套“不是……而是……”。
- 语气随题材调整：生活随笔可以亲近，政策、医疗和专业说明仍须准确克制；不为温暖牺牲主题和实用信息。`;

const endingCraft=`结尾的自然互动：
- 先把文章自己的观察、判断或下一步落稳，再决定是否与读者互动。话题有可分享的经历、具体选择或尚待讨论的细节时，可以在末尾留一句读者容易回答的问题；最多一个问题，不给每篇硬加。
- 问题必须接住正文的具体处境，例如询问某个实际做法、经历中的一个细节或选择时最在意的事。不要用放在哪篇都成立的“你怎么看”“欢迎留言讨论”，不索要点赞、转发或关注，不反复提问，也不预设读者一定有同样经历。
- 新闻通报、严肃损失、哀伤叙述或需要明确操作结论的内容，若互动会打断情绪或削弱信息，就平实收束或留白。涉及隐私的题材不邀请读者公开个人身份、联系方式或敏感经历。
- 标题已经设问时，正文先回答它；结尾不重复标题问题。互动是可选的内容延伸，不是客服式的帮忙邀约。`;

function writingDirection(style,mode){
  const taskMode=['article','outline','titles','polish','humanize'].includes(mode)?mode:'article';
  const tone=styleGuides[style]||styleGuides['自然叙述'];
  const task={
    article:'写成一篇有明确观察和真实阅读节奏的原创文章。不要把文章做成均匀铺开的观点清单。材料有人的处境时，把这层处境写具体；材料偏信息性时，也不要硬加故事。内部比较三个有不同切口的标题，选最贴合本文的一条交付，不输出备选标题或评选过程。',
    outline:'大纲呈现观点如何逐步形成、哪里需要事实支撑、哪里适合停顿或转折。各部分长短可以不同，不套固定四段式；每点写明推进作用，不写空泛标题。',
    titles:'十个标题要在观察角度、语气和信息重心上有所区别。优先准确和具体；可以有张力，但不夸大事实、不制造恐慌、不用标题党反问。',
    polish:'在保持原意、事实、作者立场和必要结构的前提下，改善可读性与节奏。优先小幅编辑；自然的句子保留，不为显示改动而重写，不把作者改成另一种人格。',
    humanize:'忠实编辑已有原稿。清除确实空转、机械和重复的表达；让句子回到原作者的意思与语气。素材已经包含真实的人情或矛盾时可让它更清楚，但不能给作者或当事人新增感受、经历或细节。'
  }[taskMode];
  return `${task}\n当前表达风格（作为方向而非固定模板）：${tone}\n\n${craftPrinciples}${['article','titles'].includes(taskMode)?'\n\n'+titleCraft:''}${taskMode==='article'?'\n\n'+endingCraft:''}`;
}

module.exports={styleGuides,craftPrinciples,titleCraft,endingCraft,writingDirection};
